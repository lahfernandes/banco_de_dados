USE BD_SUPERMERCADO_GRICK;

/* VIEW:
- VIEW SÃO PSEUDO-TABELAS QUE GRAVAM SQL GRANDES PARA SEREM EXECUTADOS EM DIVERSAS PARTES PARTES DO CÓDIGO, SEM PRECISAR REESCREVER O SELECT.
*/
-- CRIAR UMA VIEW PARA RETORNAR OS FUNCIONÁRIOS E OS SEUS SUPERMERCADOS
CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADOS AS 
SELECT	F.FUN_NOME AS "NOME",
		F.FUN_CPF	AS "CPF",
		F.FUN_DATA_NASCIMENTO AS "DATA DE NASCIMENTO",
        F.FUN_TELEFONE AS "TELEFONE",
        F.FUN_EMAIL AS "E-MAIL",
        F.FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRABALHO",
        F.FUN_BANCO_AGENCIA AS  "AGÊNCIA DO BANCO",
        F.FUN_BANCO_CONTA AS "CONTA DO BANCO",
        F.F.FUN_DATA_ADMISSAO AS "DATA DE ADMISSÃO",
        F.FUN_JORNADA_TRABALHO AS "JORNADA DE TRABALHO",
        S.SUP_RAZAO_SOCIAL AS "SUPERMERCADO QUE TRABALHA"
FROM	FUNCIONARIO F
JOIN	SUPERMERCADO S ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);
        
